// 傾聴ゲーム用のランダム質問（聞き手が相手に投げかける質問）
export const LISTENING_QUESTIONS = [
  '今日いちばんうれしかったことは何ですか？',
  '最近、どんなことで悩んでいますか？',
  'いま一番関心があることは何ですか？',
  '最近、印象に残った出来事はありますか？',
  'いまの気持ちを一言で表すと？',
  'この話題について、もう少し詳しく教えてもらえますか？',
  'それについて、どんな風に感じていますか？',
  'ほかに話したいことはありますか？',
  'いつもどんなときにリラックスできますか？',
  '最近、誰かに感謝したことはありますか？',
  'これからやってみたいことは何ですか？',
  '子どものころ、好きだったことは何ですか？',
  '最近、新しい発見はありましたか？',
  'もし叶うなら、どんなことをしたいですか？',
  '今週、よくできたと思うことは何ですか？',
  '最近、感動したことはありますか？',
  '自分を褒めるとしたら、どんなところですか？',
  '最近、誰かに支えてもらったことはありますか？',
  '10年後の自分は、どんな風になっていたいですか？',
  '最近、笑ったのはいつですか？何で笑いましたか？',
];

/** roomIdから同じ質問を選ぶ（両者で一致させる） */
export function getQuestionForRoom(roomId: string): string {
  let hash = 0;
  for (let i = 0; i < roomId.length; i++) {
    hash = (hash << 5) - hash + roomId.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % LISTENING_QUESTIONS.length;
  return LISTENING_QUESTIONS[index];
}
